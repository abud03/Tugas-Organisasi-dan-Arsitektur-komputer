from dataclasses import dataclass


@dataclass
class Instruction:
    name: str
    destination: str
    sources: list


instructions = [
    Instruction("I1", "R1", ["R2", "R3"]),
    Instruction("I2", "R4", ["R1", "R5"]),
    Instruction("I3", "R6", ["R4", "R7"]),
    Instruction("I4", "R8", ["R9", "R10"]),
]


def detect_raw(instructions):
    print("DEPENDENCY ANALYSIS - RAW")
    dependencies = []

    for i in range(len(instructions)):
        for j in range(i + 1, len(instructions)):
            first = instructions[i]
            second = instructions[j]

            if first.destination in second.sources:
                dependencies.append((first.name, second.name))
                print(
                    f"{first.name} -> {second.name} "
                    f"(Register: {first.destination})"
                )

    if not dependencies:
        print("No RAW dependencies found.")

    return dependencies


def show_dependency_graph(dependencies):
    print("\nDEPENDENCY GRAPH - RAW")

    if not dependencies:
        print("Tidak ada panah ketergantungan.")
        return

    for source, target in dependencies:
        print(f"{source} ----> {target}")


if __name__ == "__main__":
    raw_dependencies = detect_raw(instructions)
    show_dependency_graph(raw_dependencies)